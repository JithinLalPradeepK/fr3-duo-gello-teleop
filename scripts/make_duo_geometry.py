#!/usr/bin/env python3
"""Generate config/duo_geometry.yaml from the franka_description package (run once; commit the result).

  python3 scripts/make_duo_geometry.py [--description ~/gello_deps_ws/src/franka_description] [--check]

Contents of the generated file (numbers only, so the repo is self-contained and the guard needs no ROS/URDF):
  joints    FR3 joint origins (franka_description robots/fr3/kinematics.yaml), joint1..joint8 (joint8 = flange)
  bases     base pose of the left / right arm in the Duo mount frame (robots/fr3_duo/fr3_duo_mount/kinematics.yaml)
  capsules  per link (link0..link7, in the link frame): 1-2 bounding capsules [[x0,y0,z0],[x1,y1,z1],radius],
            fitted to the FR3 COLLISION meshes (meshes/robot_arms/fr3/collision/linkN.stl): every mesh vertex is
            inside a capsule, so the capsules enclose the real collision geometry (conservative).
Hand-edited settings (margins, gripper capsule, ignored pairs) live in config/duo_guard.yaml.
"""
import argparse
import os

import numpy as np
import yaml

DEMO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DEMO, 'config', 'duo_geometry.yaml')


def read_stl(path):
    b = open(path, 'rb').read()
    if b[:5] == b'solid' and b'facet' in b[:400]:
        v = [[float(x) for x in line.split()[1:4]] for line in b.decode().splitlines()
             if line.strip().startswith('vertex')]
        return np.array(v)
    n = int(np.frombuffer(b[80:84], dtype='<u4')[0])
    d = np.frombuffer(b[84:84 + 50 * n], dtype=np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')]))
    return d['v'].reshape(-1, 3).astype(float)


def seg_dist_points(p, a, b):
    ab = b - a
    L2 = float(ab @ ab)
    t = np.zeros(len(p)) if L2 < 1e-12 else np.clip(((p - a) @ ab) / L2, 0, 1)
    return np.linalg.norm(p - (a + t[:, None] * ab), axis=1)


def fit_capsule(P):
    """Smallest-volume capsule (of a small family around the principal axis) that contains all points P."""
    c = P.mean(0)
    u, s, vt = np.linalg.svd(P - c, full_matrices=False)
    ax = vt[0]
    t = (P - c) @ ax
    perp = np.linalg.norm((P - c) - t[:, None] * ax, axis=1)
    r0 = perp.max()
    best = None
    for k in np.linspace(0.0, 1.0, 21):
        t0, t1 = t.min() + k * r0, t.max() - k * r0
        if t0 > t1:
            t0 = t1 = 0.5 * (t.min() + t.max())
        a, b = c + t0 * ax, c + t1 * ax
        R = seg_dist_points(P, a, b).max()
        vol = np.pi * R * R * (t1 - t0) + 4 / 3 * np.pi * R ** 3
        if best is None or vol < best[0]:
            best = (vol, a, b, R)
    return best[1], best[2], best[3]


def fit_link(P, parts):
    """parts capsules: split the vertices into equal-count slices along the principal axis, fit each."""
    if parts == 1:
        return [fit_capsule(P)]
    c = P.mean(0)
    ax = np.linalg.svd(P - c, full_matrices=False)[2][0]
    t = (P - c) @ ax
    edges = np.quantile(t, np.linspace(0, 1, parts + 1))
    out = []
    for i in range(parts):
        sel = (t >= edges[i]) & ((t <= edges[i + 1]) if i == parts - 1 else (t < edges[i + 1]))
        out.append(fit_capsule(P[sel]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--description', default=os.path.expanduser('~/gello_deps_ws/src/franka_description'))
    ap.add_argument('--check', action='store_true', help='compare with the committed file, write nothing')
    a = ap.parse_args()
    rob = os.path.join(a.description, 'robots')
    kin = yaml.safe_load(open(os.path.join(rob, 'fr3', 'kinematics.yaml')))
    mount = yaml.safe_load(open(os.path.join(rob, 'fr3_duo', 'fr3_duo_mount', 'kinematics.yaml')))
    out = {'source': 'franka_description robots/fr3/kinematics.yaml, robots/fr3_duo/fr3_duo_mount/kinematics.yaml, '
                     'meshes/robot_arms/fr3/collision/*.stl (generated by scripts/make_duo_geometry.py)',
           'joints': {}, 'bases': {}, 'capsules': {}}
    for i in range(1, 9):
        k = kin[f'joint{i}']['kinematic']
        out['joints'][f'joint{i}'] = [float(k[x]) for x in ('x', 'y', 'z', 'roll', 'pitch', 'yaw')]
    for arm in ('left', 'right'):
        k = mount[arm]['kinematic']
        out['bases'][arm] = [float(k[x]) for x in ('x', 'y', 'z', 'roll', 'pitch', 'yaw')]
    parts = {0: 1, 1: 1, 2: 2, 3: 3, 4: 3, 5: 3, 6: 3, 7: 1}
    for i in range(8):
        P = read_stl(os.path.join(a.description, 'meshes', 'robot_arms', 'fr3', 'collision', f'link{i}.stl'))
        caps = fit_link(P, parts[i])
        out['capsules'][f'link{i}'] = [[[round(float(x), 4) for x in p0], [round(float(x), 4) for x in p1],
                                        round(float(R), 4)] for p0, p1, R in caps]
        # every vertex must be inside one of the capsules
        d = np.min([seg_dist_points(P, p0, p1) - R for p0, p1, R in caps], axis=0)
        print(f'link{i}: {len(P)} vertices, {len(caps)} capsule(s), radii {[round(float(c[2]), 3) for c in caps]}, '
              f'max vertex outside {max(0, float(d.max())):.4f} m')
        assert d.max() < 1e-3, f'link{i}: vertices outside the fitted capsules'
    if a.check:
        old = yaml.safe_load(open(OUT))
        print('identical to committed file' if old == out else 'DIFFERENT from committed file')
        return
    with open(OUT, 'w') as f:
        f.write('# GENERATED by scripts/make_duo_geometry.py - do not edit (margins etc.: config/duo_guard.yaml)\n')
        yaml.safe_dump(out, f, default_flow_style=None, sort_keys=False)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
